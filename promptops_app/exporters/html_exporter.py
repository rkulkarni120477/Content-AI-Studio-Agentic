"""HTML export engine — five templates.

Templates
---------
default       — Standard styled course document (original behavior).
storyboard    — Scene-card layout for video/animation production teams.
teacher_guide — Learner content + instructor Teaching Notes box per block.
quiz_bank     — Q&A-only extraction for assessment teams.
client        — Clean minimal layout for client delivery.

All functions return a str (complete HTML document).
"""

from __future__ import annotations

from datetime import datetime, timezone


# ---------------------------------------------------------------------------
# Shared CSS blocks
# ---------------------------------------------------------------------------

_BASE_CSS = """
  body {
    font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;
    max-width: 960px; margin: 50px auto; padding: 0 24px;
    line-height: 1.8; color: #1e293b; background: #fafbfc;
  }
  h1 { color: #2563eb; border-bottom: 3px solid #2563eb; padding-bottom: 10px; }
  h2 { color: #1e40af; margin-top: 2rem; }
  h3 { color: #334155; }
  section { margin-bottom: 2.5rem; }
  hr  { border: none; border-top: 1px solid #e2e8f0; margin: 2rem 0; }
  .footer { text-align: center; color: #94a3b8; font-size: 0.82rem;
            margin-top: 3rem; padding: 1rem; border-top: 1px solid #e2e8f0; }
  .meta  { color: #64748b; font-size: 0.85rem; margin-bottom: 1.5rem; }
"""

_BRAND_FOOTER = "Powered by Content AI Studio · AI-Generated eLearning Content"

_NOW = lambda: datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _wrap(title: str, css: str, body: str, meta: str = "") -> str:
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{title}</title>
  <style>{css}</style>
</head>
<body>
  <h1>📚 {title}</h1>
  {f'<p class="meta">{meta}</p>' if meta else ""}
  {body}
  <div class="footer">{_BRAND_FOOTER}</div>
</body>
</html>"""


# ---------------------------------------------------------------------------
# Template: default
# ---------------------------------------------------------------------------

def _default(topic: str, blocks: list[tuple[str, str]]) -> str:
    sections = "".join(
        f"<section><h2>{lbl}</h2><div>{cnt.replace(chr(10), '<br>')}</div></section><hr/>"
        for lbl, cnt in blocks
    )
    return _wrap(topic, _BASE_CSS, sections,
                 meta=f"Generated by Content AI Studio · {_NOW()}")


