_CLIENT_CSS = """
  body {
    font-family: 'Georgia', 'Times New Roman', serif;
    max-width: 860px; margin: 60px auto; padding: 0 32px;
    line-height: 1.9; color: #111827; background: #fff;
  }
  h1 { color: #111827; border-bottom: 2px solid #111827; padding-bottom: 8px;
       font-size: 1.8rem; }
  h2 { color: #1f2937; font-size: 1.2rem; margin-top: 2.5rem;
       text-transform: uppercase; letter-spacing: .06em; }
  section { margin-bottom: 3rem; }
  hr  { border: none; border-top: 1px solid #d1d5db; margin: 2.5rem 0; }
  .footer { text-align: center; color: #9ca3af; font-size: 0.78rem;
            margin-top: 4rem; padding-top: 1rem; border-top: 1px solid #e5e7eb; }
  .cover  { text-align: center; margin-bottom: 4rem; }
  .cover p { color: #6b7280; font-size: 0.95rem; }
"""


def _client(topic: str, blocks: list[tuple[str, str]]) -> str:
    sections = "".join(
        f"<section><h2>{lbl}</h2><p>{cnt.replace(chr(10), '</p><p>')}</p></section><hr/>"
        for lbl, cnt in blocks
    )
    cover = f'<div class="cover"><h1>{topic}</h1><p>Prepared for Client Review</p><p>{_NOW()}</p></div>'
    return _wrap(topic, _CLIENT_CSS, cover + sections)


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------

TEMPLATES = {
    "default":       _default,
    "storyboard":    _storyboard,
    "teacher_guide": _teacher_guide,
    "quiz_bank":     _quiz_bank,
    "client":        _client,
}


def build_html(topic: str, blocks: list[tuple[str, str]], template: str = "default") -> str:
    """Build a complete HTML document for the given template.

    ``blocks`` is a list of (label, content) string tuples.
    Falls back to "default" for unknown template names.
    """
    fn = TEMPLATES.get(template, _default)
    return fn(topic, blocks)
