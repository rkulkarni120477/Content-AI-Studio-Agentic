def _build_prompt_md(
    *,
    project_name: str,
    cluster_name: str,
    course_name: str,
    component: str,
    prompt_name: str,
    prompt_version: str,
    system_prompt: str,
    user_prompt_template: str,
    extra_instructions: str,
    is_ai_override: bool = False,
) -> str:
    """Build a Markdown-formatted prompt download string with full context metadata."""
    from datetime import datetime, timezone
    ts          = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    comp_label  = _COMP_LABELS.get(component, component.title())
    ver_display = f"{prompt_version}" + (" *(AI-improved — not saved)*" if is_ai_override else "")

    lines = [
        f"# Prompt Download — {comp_label}",
        f"",
        f"> **Downloaded:** {ts}",
        f"",
        f"---",
        f"",
        f"## Context",
        f"",
        f"| Field | Value |",
        f"|---|---|",
        f"| **Project** | {project_name or '—'} |",
    ]
    if cluster_name:
        lines.append(f"| **Cluster** | {cluster_name} |")
    if course_name:
        lines.append(f"| **Course** | {course_name} |")
    lines += [
        f"| **Component** | {comp_label} |",
        f"| **Prompt Asset** | {prompt_name or '—'} |",
        f"| **Version** | {ver_display} |",
        f"",
        f"---",
        f"",
        f"## System Prompt",
        f"",
        system_prompt.strip() if system_prompt else "*(none)*",
        f"",
        f"---",
        f"",
        f"## User Prompt Template",
        f"",
        user_prompt_template.strip() if user_prompt_template else "*(none)*",
        f"",
    ]
    if extra_instructions and extra_instructions.strip():
        lines += [
            f"---",
            f"",
            f"## Additional Instructions",
            f"",
            extra_instructions.strip(),
            f"",
        ]
    lines += ["---", "", "*Generated by Content AI Studio*"]
    return "\n".join(lines)


