def render_prompt_download_button(
    db,
    component: str,
    project_name: str = "",
    cluster_name: str = "",
    course_name: str = "",
    button_label: str = "⬇️ Download Prompt Used",
    key: str = "",
    use_container_width: bool = False,
    help_text: str = "Download the prompt used for generation as a Markdown file.",
) -> None:
    """Standalone download button — place near any component's content download buttons.

    Reads the currently-selected prompt from session state (set by
    render_inline_prompt_controls for the same component).
    """
    _PFX      = f"_gc_{component}"
    _SEL_KEY  = f"{_PFX}_sel"
    _EXTRA_KEY = f"{_PFX}_extra"
    _OVRD_SYS = f"{_PFX}_override_sys"
    _OVRD_USR = f"{_PFX}_override_usr"

    sel_label      = st.session_state.get(_SEL_KEY, "")
    extra          = st.session_state.get(_EXTRA_KEY, "")
    override_sys   = st.session_state.get(_OVRD_SYS)
    override_usr   = st.session_state.get(_OVRD_USR)
    is_ai_override = override_sys is not None or override_usr is not None

    prompt_name    = ""
    prompt_version = "—"
    sys_p          = override_sys or ""
    usr_p          = override_usr or ""

    # Look up prompt details from DB when not using an AI override
    _label_map: dict[str, Prompt] = {}
    try:
        for p in prompt_repository.list_prompts_by_component(db, component):
            lbl = _display_label(p)
            if lbl not in _label_map:
                _label_map[lbl] = p
        for p in prompt_repository.list_prompts_tagged(db, component):
            if p.component_type != component:
                lbl = _display_label(p)
                if lbl not in _label_map:
                    _label_map[lbl] = p
    except Exception:
        pass

    _sel_p = _label_map.get(sel_label)
    if _sel_p is None:
        # Fall back to the default prompt for this component
        try:
            _sel_p = prompt_repository.get_default_prompt(db, component)
        except Exception:
            pass

    if _sel_p is not None:
        prompt_name    = _sel_p.name
        prompt_version = _sel_p.active_version or "v1"
        if not sys_p or not usr_p:
            try:
                _ver = prompt_repository.get_active_version(db, _sel_p.id)
                if _ver:
                    sys_p = sys_p or (_ver.system_prompt or "")
                    usr_p = usr_p or (_ver.user_prompt_template or "")
            except Exception:
                pass

    _md = _build_prompt_md(
        project_name=project_name,
        cluster_name=cluster_name,
        course_name=course_name,
        component=component,
        prompt_name=prompt_name,
        prompt_version=prompt_version,
        system_prompt=sys_p,
        user_prompt_template=usr_p,
        extra_instructions=extra,
        is_ai_override=is_ai_override,
    )
    _safe_ver  = (prompt_version or "v1").replace("/", "-").replace(" ", "_")
    _safe_comp = component.lower()
    _fname     = f"prompt_{_safe_comp}_{_safe_ver}.doc"

    st.download_button(
        button_label,
        data=_md,
        file_name=_fname,
        mime="application/msword",
        use_container_width=use_container_width,
        key=key or f"{_PFX}_standalone_dl",
        help=help_text,
    )


def _display_label(p: Prompt) -> str:
    if p.is_default:
        comp = _COMP_LABELS.get(p.component_type or "", p.component_type or "")
        return f"🏷️ Default {comp} Prompt"
    return p.name


