def _improve_prompt_with_llm(cur_sys: str, cur_usr: str, instructions: str, model_choice: str) -> dict:
    """Call the active LLM to improve an existing prompt.

    Returns a dict with keys ``system_prompt`` and ``user_prompt_template``.
    Falls back to the originals on any failure so the caller always gets a dict.
    """
    _IMPROVE_SYSTEM = (
        "You are an expert prompt engineer specialising in instructional design AI systems. "
        "Your task is to improve an existing LLM prompt based on user feedback. "
        "Preserve all placeholder variables (e.g. {course_title}, {topic}). "
        "Return ONLY valid JSON with exactly two keys: "
        "\"system_prompt\" and \"user_prompt_template\". No markdown, no explanation."
    )
    _IMPROVE_USER = (
        "CURRENT SYSTEM PROMPT:\n{sys}\n\n"
        "CURRENT USER PROMPT TEMPLATE:\n{usr}\n\n"
        "IMPROVEMENT INSTRUCTIONS:\n{instr}\n\n"
        "Return the improved prompts as JSON:\n"
        "{{\"system_prompt\": \"...\", \"user_prompt_template\": \"...\"}}"
    ).format(sys=cur_sys[:1200], usr=cur_usr[:1200], instr=instructions)

    try:
        from promptops_app.services.llm_service import generate_text as _call
        from promptops_app.core.llm_client import safe_json_loads
        raw = _call(model_choice, _IMPROVE_SYSTEM, _IMPROVE_USER)
        if isinstance(raw, str) and raw.startswith("ERROR"):
            raise ValueError(raw)
        parsed = safe_json_loads(raw)
        if isinstance(parsed, dict) and ("system_prompt" in parsed or "user_prompt_template" in parsed):
            return {
                "system_prompt":        parsed.get("system_prompt", cur_sys),
                "user_prompt_template": parsed.get("user_prompt_template", cur_usr),
            }
        raise ValueError("Unexpected response shape")
    except Exception:
        return {"system_prompt": cur_sys, "user_prompt_template": cur_usr}


